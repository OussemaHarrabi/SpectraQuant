#!/usr/bin/env python
"""Generate the published tables and figures from the committed artifacts.

Every file under ``reports/tables/`` and ``reports/figures/`` is produced *only* by this script,
which reads the committed JSON artifacts under ``artifacts/sample-results/``. Nothing is typed by
hand, so a table or figure cannot drift from the artifact it summarises: re-running the script (or
the regression test ``tests/unit/test_release_artifacts.py``) reproduces the committed bytes.

The script is pure standard library and deterministic; it contains no timestamps, no RNG and no
network access. The Pareto figure is emitted as SVG so that no plotting dependency is added.

Usage::

    uv run python scripts/reproduce/generate_release_artifacts.py            # write committed paths
    uv run python scripts/reproduce/generate_release_artifacts.py --out DIR  # write to DIR instead

Measurement-class and substrate labels are carried through verbatim from each artifact; see
``AGENTS.md`` section 5 for the taxonomy.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
ARTIFACT_ROOT = REPO_ROOT / "artifacts" / "sample-results"
DEFAULT_OUT = REPO_ROOT / "reports"

# Artifact paths (relative to the artifact root) are quoted in every generated file header so a
# reader can trace each number back to its source document.
PROXY_VALIDATION = "proxy-validation/proxy-validation.json"
PROXY_FIXTURE = "proxy-fixture/proxy-fixture.json"
FRONTIER = "allocation-frontier/frontier.json"
CLASS4CPU = "class4cpu/class4cpu.json"
REGULARIZER = "regularizer/sweep.json"

_SOLVER_ORDER = ("uniform", "greedy", "ortools")
_SOLVER_COLORS = {"uniform": "#1f77b4", "greedy": "#ff7f0e", "ortools": "#2ca02c"}
_VARIANT_ORDER = (
    "weight_frobenius",
    "weight_magnitude",
    "activation_magnitude",
    "per_layer_output_error",
    "in_situ_output_error",
    "gain_aware_composed",
    "hessian_diag",
    "quant_residual_stats",
    "spectral_summary",
    "combined",
)


def _load(relative: str) -> dict[str, Any]:
    with (ARTIFACT_ROOT / relative).open(encoding="utf-8") as handle:
        return json.load(handle)


def _num(value: float | int | None, digits: int = 6) -> str:
    """Format a number deterministically at ``digits`` significant figures."""
    if value is None:
        return "n/a"
    if isinstance(value, int) or float(value).is_integer():
        return str(int(value))
    return f"{value:.{digits}g}"


def _mean_sd(metrics: dict[str, Any], key: str) -> str:
    entry = metrics[key]
    return f"{entry['mean']:.6g} +/- {entry['std']:.4g}"


def _banner(title: str, artifact: str, note: str) -> str:
    return (
        f"<!-- Generated by scripts/reproduce/generate_release_artifacts.py from "
        f"artifacts/sample-results/{artifact}. Do not edit by hand. -->\n\n"
        f"# {title}\n\n"
        f"{note}\n"
    )


