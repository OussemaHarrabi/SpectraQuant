def figure_pareto() -> str:
    doc = _load(FRONTIER)
    points: list[tuple[float, float, str, int]] = []
    for point in doc["points"]:
        for solver in _SOLVER_ORDER:
            arm = point["arms"][solver]
            points.append(
                (
                    float(arm["measured_bytes"]),
                    float(arm["measured_hidden_damage"]),
                    solver,
                    int(point["budget_bytes"]),
                )
            )
    width, height = 900, 620
    margin = {"left": 90, "right": 220, "top": 70, "bottom": 80}
    plot_w = width - margin["left"] - margin["right"]
    plot_h = height - margin["top"] - margin["bottom"]
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    x_min, x_max = min(xs) * 0.9, max(xs) * 1.05
    y_min, y_max = 0.0, max(ys) * 1.08

    def sx(value: float) -> float:
        return margin["left"] + (value - x_min) / (x_max - x_min) * plot_w

    def sy(value: float) -> float:
        return margin["top"] + plot_h - (value - y_min) / (y_max - y_min) * plot_h

    parts: list[str] = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" font-family="Helvetica, Arial, sans-serif">',
        '<rect width="100%" height="100%" fill="#ffffff"/>',
        f'<text x="{width / 2:.0f}" y="30" text-anchor="middle" font-size="19" '
        'font-weight="bold">Allocator frontier: measured hidden-state damage vs measured bytes</text>',
        f'<text x="{width / 2:.0f}" y="52" text-anchor="middle" font-size="12" fill="#555">'
        "Substrate LOCAL-FIXTURE (one seed, 13 modules, synthetic task) | classes 1/2/3 | "
        "NOT the confirmatory H4 cell (NOT RUN)</text>",
    ]
    # Axes
    parts.append(
        f'<line x1="{margin["left"]}" y1="{margin["top"]}" x2="{margin["left"]}" '
        f'y2="{margin["top"] + plot_h}" stroke="#333" stroke-width="1.2"/>'
    )
    parts.append(
        f'<line x1="{margin["left"]}" y1="{margin["top"] + plot_h}" '
        f'x2="{margin["left"] + plot_w}" y2="{margin["top"] + plot_h}" stroke="#333" '
        'stroke-width="1.2"/>'
    )
    for tick_bytes in doc["budgets"]["ladder_bytes"]:
        x = sx(float(tick_bytes))
        parts.append(
            f'<line x1="{x:.1f}" y1="{margin["top"] + plot_h}" x2="{x:.1f}" '
            f'y2="{margin["top"] + plot_h + 5}" stroke="#333"/>'
        )
        parts.append(
            f'<text x="{x:.1f}" y="{margin["top"] + plot_h + 20}" text-anchor="middle" '
            f'font-size="11">{tick_bytes}</text>'
        )
    for frac in (0.0, 0.25, 0.5, 0.75, 1.0):
        value = y_min + frac * (y_max - y_min)
        y = sy(value)
        parts.append(
            f'<line x1="{margin["left"] - 5}" y1="{y:.1f}" x2="{margin["left"]}" '
            f'y2="{y:.1f}" stroke="#333"/>'
        )
        parts.append(
            f'<text x="{margin["left"] - 8}" y="{y + 4:.1f}" text-anchor="end" font-size="11">'
            f"{value:.2f}</text>"
        )
    parts += [
        f'<text x="{margin["left"] + plot_w / 2:.0f}" y="{height - 38}" text-anchor="middle" '
        'font-size="13">measured stored bytes (class 3)</text>',
        f'<text transform="translate(24,{margin["top"] + plot_h / 2:.0f}) rotate(-90)" '
        'text-anchor="middle" font-size="13">measured hidden-state damage (class 2)</text>',
    ]
    # Equal-memory wins: draw a connector between the uniform point and the winning mixed point.
    for win in doc["equal_memory_wins"]:
        budget = int(win["budget_bytes"])
        reference = next(p for p in doc["points"] if p["budget_bytes"] == budget)["arms"]["uniform"]
        mixed = next(p for p in doc["points"] if p["budget_bytes"] == budget)["arms"][
            win["candidate"]
        ]
        parts.append(
            f'<line x1="{sx(float(reference["measured_bytes"])):.1f}" '
            f'y1="{sy(float(reference["measured_hidden_damage"])):.1f}" '
            f'x2="{sx(float(mixed["measured_bytes"])):.1f}" '
            f'y2="{sy(float(mixed["measured_hidden_damage"])):.1f}" stroke="#999" '
            'stroke-width="1" stroke-dasharray="4 3"/>'
        )
        parts.append(
            f'<text x="{(sx(float(reference["measured_bytes"])) + sx(float(mixed["measured_bytes"]))) / 2:.1f}" '
            f'y="{(sy(float(reference["measured_hidden_damage"])) + sy(float(mixed["measured_hidden_damage"]))) / 2 - 6:.1f}" '
            f'text-anchor="middle" font-size="10" fill="#666">'
            f"{win['candidate']} {win['budget_bytes']}B ratio {win['hidden_damage_ratio']:.3f}</text>"
        )
    # Markers
    for x_value, y_value, solver, budget in points:
        parts.append(
            f'<circle cx="{sx(x_value):.1f}" cy="{sy(y_value):.1f}" r="5" '
            f'fill="{_SOLVER_COLORS[solver]}" stroke="#222" stroke-width="0.6">'
            f"<title>{solver}: budget {budget} B, measured {x_value:.0f} B, "
            f"hidden damage {y_value:.4f}</title></circle>"
        )
    # Legend
