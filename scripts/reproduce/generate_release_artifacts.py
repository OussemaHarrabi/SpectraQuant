def generate(out_dir: Path) -> list[Path]:
    """Write every table and figure under ``out_dir``; return the written paths."""
    tables_dir = out_dir / "tables"
    figures_dir = out_dir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for filename, builder in TABLES.items():
        target = tables_dir / filename
        target.write_text(builder(), encoding="utf-8", newline="\n")
        written.append(target)
    for filename, builder in FIGURES.items():
        target = figures_dir / filename
        target.write_text(builder(), encoding="utf-8", newline="\n")
        written.append(target)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", type=Path, default=DEFAULT_OUT, help="output root (default: reports/)"
    )
    args = parser.parse_args(argv)
    written = generate(args.out)
    for path in written:
        print(path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path)
    return 0


