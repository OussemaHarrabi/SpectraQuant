def table_proxy_ranking() -> str:
    doc = _load(PROXY_VALIDATION)
    plan = doc["plan"]
    predeclared = doc["predeclared_mde"]
    lines = [
        _banner(
            "Proxy-ranking table (Milestone 4, local fixture)",
            PROXY_VALIDATION,
            f"Substrate `{doc['substrate']}`; measurement class **{doc['measurement_class']}** "
            f"(fake-quantization quality). Seeds {doc['runs']['seeds']} x cells {plan['cells']} x "
            f"fixtures {plan['fixtures']}; statistical unit: **{doc['statistical_unit']}**. "
            f"Predeclared MDE(z) {predeclared['mde_z_optimistic']} "
            f"(n_eff={predeclared['n_eff_optimistic']}) to {predeclared['mde_z_conservative']} "
            f"(n_eff={predeclared['n_eff_conservative']}) at S={predeclared['seeds']} seeds. "
            "Deltas are candidate minus comparator Fisher-z; the verdict follows the analytic "
            "random-effects CI.",
        ),
        "## 1. Per-cell Spearman rho (mean over seeds, model-level, vs single-layer damage)",
        "",
        "| fixture | rank | bits | " + " | ".join(f"`{v}`" for v in _VARIANT_ORDER) + " |",
        "|---|---|---|" + "---|" * len(_VARIANT_ORDER),
    ]
    for cell in doc["per_cell"]:
        values = " | ".join(f"{cell['variants'][v]['rho_mean']:+.3f}" for v in _VARIANT_ORDER)
        lines.append(f"| {cell['fixture']} | {cell['rank']} | {cell['bits']} | {values} |")
    lines += [
        "",
        "## 2. Model-level aggregation (Fisher-z random effects over clusters)",
        "",
        "| fixture group | candidate | rho_mean | z pooled | z CI | k units | n_eff mean | "
        "achieved MDE(z) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for group in ("layernorm", "no_layernorm", "all_fixtures"):
        block = doc["aggregate"][group]
        for name in _VARIANT_ORDER:
            variant = block["variants"][name]
            lines.append(
                f"| {group} | `{name}` | {variant['rho_mean']:+.4f} | "
                f"{variant['pooled']:+.4f} | [{variant['ci'][0]:+.4f}, {variant['ci'][1]:+.4f}] | "
                f"{variant['k']} | {variant['n_eff_mean']:+.3f} | {block['mde']['achieved_z']:+.4f} |"
            )
    lines += [
        "",
        "## 3. Predeclared candidate contrasts (candidate minus comparator)",
        "",
        "| fixture group | candidate | comparator | delta_z | random-effects CI | p | verdict |",
        "|---|---|---|---|---|---|---|",
    ]
    comparators = [*plan["predeclared_comparators"], plan["naive_baseline"]]
    for group in ("layernorm", "no_layernorm", "all_fixtures"):
        block = doc["aggregate"][group]
        for candidate in ("combined", "gain_aware_composed"):
            contrasts = block["contrasts"][candidate]
            for comparator in comparators:
                entry = contrasts[comparator]
                lines.append(
                    f"| {group} | `{candidate}` | `{comparator}` | {entry['delta_z']:+.4f} | "
                    f"[{entry['ci'][0]:+.4f}, {entry['ci'][1]:+.4f}] | {_num(entry['p_value'])} | "
                    f"{entry['verdict']['verdict']} |"
                )
    lines += [
        "",
        "## 4. Cloud confirmatory cells",
        "",
        "| cell | hypothesis | tier | substrate | status |",
        "|---|---|---|---|---|",
    ]
    for cell in doc["cloud_cells"].values():
        lines.append(
            f"| {cell['confirmatory_cell']} | {cell['hypothesis']} | {cell['tier']} | "
            f"`{cell['substrate']}` | **{cell['status']}** |"
        )
    lines += [
        "",
        "Every number above is class "
        f"{doc['measurement_class']} on the `{doc['substrate']}` substrate; no storage, kernel or "
        "latency claim is made here.",
        "",
    ]
    return "\n".join(lines)


def table_allocator_frontier() -> str:
    doc = _load(FRONTIER)
    classes = doc["measurement_classes"]
    lines = [
        _banner(
            "Allocator frontier table (Milestone 6, local fixture)",
            FRONTIER,
            f"Substrate `{doc['substrate']}`; {doc['scope']}. Classes: accounted_bytes="
            f"{classes['accounted_bytes']}, measured_bytes={classes['measured_bytes']}, "
            f"predicted_error={classes['predicted_error']}, measured_hidden_damage="
            f"{classes['measured_hidden_damage']}. Compression grid: ranks {doc['compression']['ranks']},"
            f" bits {doc['compression']['bits']}, group_size {doc['compression']['group_size']}, "
            f"serializer `{doc['compression']['serializer']}`.",
        ),
        "| budget B (class 1) | solver | accounted B | measured B (class 3) | rel diff | "
        "predicted error (class 2) | hidden damage (class 2) | logits damage (class 2) | "
        "mean rank | mean bits | distinct options |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for point in doc["points"]:
        for solver in _SOLVER_ORDER:
            arm = point["arms"][solver]
            parity = arm["byte_parity"]
            lines.append(
                f"| {point['budget_bytes']} | {solver} | {arm['accounted_bytes']} | "
                f"{arm['measured_bytes']} | {parity['relative_difference']:.2e} | "
                f"{arm['predicted_error']:.6e} | {arm['measured_hidden_damage']:.6f} | "
                f"{arm['measured_logits_damage']:.6f} | {arm['mean_rank']:.4f} | "
                f"{arm['mean_bits']:.4f} | {arm['distinct_options']} |"
            )
